def agg_scores(seeds):
    """逐题对 K 个 seed 评分取中位数（复用 harness score_task）。"""
    out = {}
    for tid in RIDS:
        vals = [E.score_task(tmap[tid], s.get(tid, "")) for s in seeds]
        out[tid] = round(statistics.median(vals), 3)
    return out


base = agg_scores(baseline_seeds)
cand = agg_scores(candidate_seeds)

# per-question pass（复用 harness 阈值）
bp = {tid: E.is_pass(base[tid], tmap[tid]) for tid in RIDS}
cp = {tid: E.is_pass(cand[tid], tmap[tid]) for tid in RIDS}
b = sum(1 for tid in RIDS if bp[tid] and not cp[tid])   # base过cand挂
c = sum(1 for tid in RIDS if cp[tid] and not bp[tid])   # base挂cand过
p, _, _ = E.mcnemar_exact(b, c)
base_pass = sum(bp.values())
cand_pass = sum(cp.values())
base_mean = round(sum(base.values()) / len(RIDS), 3)
cand_mean = round(sum(cand.values()) / len(RIDS), 3)

print("=== REASONING-AXIS GATE (T038-T046, K=5) ===")
print("baseline(direct)  per-q pass:", bp)
print("candidate(decomp) per-q pass:", cp)
print("baseline  mean=%.3f pass=%d/%d" % (base_mean, base_pass, len(RIDS)))
print("candidate mean=%.3f pass=%d/%d" % (cand_mean, cand_pass, len(RIDS)))
print("discordant: base>cand=%d, cand>base=%d" % (b, c))
print("McNemar exact p=%.4f  delta_mean=%+.3f" % (p, cand_mean - base_mean))
decision = "PROMOTE" if (cand_mean - base_mean > 0 and p < 0.05 and c > b) else \
           ("REVERT" if cand_mean - base_mean < -0.05 else "HOLD")
print("DECISION:", decision)
